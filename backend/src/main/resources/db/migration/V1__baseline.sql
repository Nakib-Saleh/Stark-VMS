-- Baseline (ADR-0007, rewritten for PostgreSQL in ADR-0008): the two tables the app had on MySQL,
-- same columns and rules. Never edit this file once it has run on a database you keep;
-- add V2__... for any change. Flyway runs it inside schema `stark` (application.properties).

CREATE TABLE vehicles (
    id                 BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    brand              VARCHAR(255) NOT NULL,
    color              VARCHAR(255),
    created_at         TIMESTAMP(6) NOT NULL,
    driver_name        VARCHAR(255),
    driver_phone       VARCHAR(255),
    fuel_type          VARCHAR(20)  NOT NULL,
    manufacturing_year INTEGER,
    model              VARCHAR(255) NOT NULL,
    seating_capacity   INTEGER,
    status             VARCHAR(20)  NOT NULL,
    updated_at         TIMESTAMP(6) NOT NULL,
    vehicle_number     VARCHAR(255) NOT NULL,
    vehicle_type       VARCHAR(20)  NOT NULL,
    company            VARCHAR(100),
    CONSTRAINT pk_vehicles PRIMARY KEY (id),
    CONSTRAINT ck_vehicles_manufacturing_year CHECK (manufacturing_year >= 1900),
    -- Postgres has no ENUM column like MySQL's; these lists do the same job. A new value needs
    -- a migration that drops and re-adds the constraint.
    CONSTRAINT ck_vehicles_fuel_type CHECK (fuel_type IN ('CNG','DIESEL','ELECTRIC','HYBRID','LPG','OCTANE','PETROL')),
    CONSTRAINT ck_vehicles_status CHECK (status IN ('AVAILABLE','INACTIVE','IN_USE','MAINTENANCE')),
    CONSTRAINT ck_vehicles_vehicle_type CHECK (vehicle_type IN ('BUS','CAR','MICROBUS','MOTORCYCLE','PICKUP','SUV','TRUCK','VAN'))
);

-- Postgres compares text case-sensitively, so uniqueness is on the upper-case number: "dha-…" and
-- "DHA-…" can't both exist (MySQL's collation did this before). The service stores upper case anyway.
-- GlobalExceptionHandler recognises a race by this name.
CREATE UNIQUE INDEX uk_vehicles_vehicle_number ON vehicles (UPPER(vehicle_number));

CREATE TABLE users (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY,
    created_at    TIMESTAMP(6) NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    username      VARCHAR(50)  NOT NULL,
    CONSTRAINT pk_users PRIMARY KEY (id)
);

-- Sign-in looks usernames up ignoring case, so two that differ only in case must not exist.
CREATE UNIQUE INDEX uk_users_username ON users (LOWER(username));
